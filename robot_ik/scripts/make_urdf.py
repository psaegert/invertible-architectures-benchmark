"""Generate robot_ik/assets/fr3/fr3.urdf from Franka's official description.

    git clone https://github.com/frankarobotics/franka_description
    git -C franka_description checkout <FRANKA_DESCRIPTION_COMMIT>
    python -m robot_ik.scripts.make_urdf path/to/franka_description

The xacro is expanded with the pip `xacro` package. Outside a ROS workspace
`$(find franka_description)` cannot be resolved, so the description is copied
to a temporary directory and those references are replaced by its path. The
arm is expanded without a hand (`hand:=false`), so the chain ends at the flange
`fr3_link8`, 0.107 m past joint 7 along its axis.

The result is then reduced to its kinematics: base, links fr3_link0..8 and the
joints between them, with origins, axes and limits. Visuals, collisions,
inertials, accelerometer frames and the self-collision sub-links are dropped;
they are not needed for forward kinematics and contain tags pytorch_kinematics
does not need to parse.
"""

import argparse
import shutil
import subprocess
import sys
import tempfile
import xml.etree.ElementTree as ET
from pathlib import Path

FRANKA_DESCRIPTION_COMMIT = '7aeeddc449edf8d62b594f9e36a81da53e7796f9'  # release 2.9.0, 2026-08-17
OUT = Path(__file__).resolve().parents[1] / 'assets' / 'fr3' / 'fr3.urdf'

KEEP_LINKS = {'base'} | {f'fr3_link{i}' for i in range(9)}
KEEP_JOINTS = {'fr3_base_joint'} | {f'fr3_joint{i}' for i in range(1, 9)}


def expand(description):
    """Run xacro on fr3.urdf.xacro and return the URDF text."""
    with tempfile.TemporaryDirectory() as tmp:
        copy = Path(tmp) / 'franka_description'
        shutil.copytree(description, copy, ignore=shutil.ignore_patterns('.git', 'meshes'))
        for f in copy.rglob('*.xacro'):
            f.write_text(f.read_text().replace('$(find franka_description)', str(copy)))
        xacro = Path(sys.executable).with_name('xacro')
        res = subprocess.run([str(xacro), str(copy / 'robots/fr3/fr3.urdf.xacro'), 'hand:=false'],
                             capture_output=True, text=True, check=True)
        return res.stdout


def reduce(urdf_text):
    """Keep only the kinematic chain base -> fr3_link8."""
    root = ET.fromstring(urdf_text)
    out = ET.Element('robot', name='fr3')
    for link in root.findall('link'):
        if link.get('name') in KEEP_LINKS:
            ET.SubElement(out, 'link', name=link.get('name'))
    for joint in root.findall('joint'):
        if joint.get('name') not in KEEP_JOINTS:
            continue
        j = ET.SubElement(out, 'joint', name=joint.get('name'), type=joint.get('type'))
        for tag in ('parent', 'child'):
            ET.SubElement(j, tag, link=joint.find(tag).get('link'))
        origin = joint.find('origin')
        ET.SubElement(j, 'origin', xyz=origin.get('xyz', '0 0 0'), rpy=origin.get('rpy', '0 0 0'))
        if joint.get('type') == 'revolute':
            ET.SubElement(j, 'axis', xyz=joint.find('axis').get('xyz'))
            lim = joint.find('limit')
            ET.SubElement(j, 'limit', {k: lim.get(k) for k in ('lower', 'upper', 'effort', 'velocity')})
    missing = (KEEP_LINKS - {l.get('name') for l in out.findall('link')}) | \
              (KEEP_JOINTS - {j.get('name') for j in out.findall('joint')})
    if missing:
        raise ValueError(f'expected elements not found in the expanded URDF: {sorted(missing)}')
    ET.indent(out)
    header = (f'<?xml version="1.0"?>\n'
              f'<!-- Generated by robot_ik/scripts/make_urdf.py from franka_description\n'
              f'     (https://github.com/frankarobotics/franka_description, Apache-2.0),\n'
              f'     commit {FRANKA_DESCRIPTION_COMMIT}, robots/fr3/fr3.urdf.xacro hand:=false.\n'
              f'     Reduced to the kinematic chain base -> fr3_link8 (flange). Do not edit by hand. -->\n')
    return header + ET.tostring(out, encoding='unicode') + '\n'


def main():
    p = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    p.add_argument('franka_description', type=Path)
    p.add_argument('--out', type=Path, default=OUT)
    args = p.parse_args()
    head = subprocess.run(['git', '-C', str(args.franka_description), 'rev-parse', 'HEAD'],
                          capture_output=True, text=True, check=True).stdout.strip()
    if head != FRANKA_DESCRIPTION_COMMIT:
        sys.exit(f'franka_description is at {head}, expected {FRANKA_DESCRIPTION_COMMIT}')
    args.out.write_text(reduce(expand(args.franka_description)))
    print(f'wrote {args.out}')


if __name__ == '__main__':
    main()
